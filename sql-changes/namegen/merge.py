#!/usr/bin/env python3
"""Merge the per-race/sex name drafts in this folder into merged_data.sql
(here in this folder).

Drafts are complete, individually runnable INSERT IGNORE files:
  fn_<race>_m.sql   -> playerbots_race_names  (first names)
  fn_<race>_f.sql
  sn_<race>.sql     -> playerbots_surnames + playerbots_surname_parts

The output is a scratch file: fold it into a new fork-local 9xxx migration in
sql/playerbot_v2 to ship it (see README.md) - upstream's 0063/0064 already
seed the tables at server startup, so never edit 0064 itself.

Usage:  python merge.py          (run from this folder)
"""
import pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "merged_data.sql"

HEADER = """\
-- merged_data.sql - scratch output, not a migration
-- GENERATED by sql-changes/namegen/merge.py - do not edit; edit the
-- sql-changes/namegen/fn_*.sql / sn_*.sql drafts and re-run merge.py.
--
-- Seeds playerbots_race_names (curated first names), playerbots_surnames
-- (whole surnames) and playerbots_surname_parts (compound halves) on the
-- PLAYERBOT shared database. All INSERT IGNORE - safe to re-run.
-- To ship: fold into a new sql/playerbot_v2/9xxx migration with {SHARED}.
-- prefixed table names (see README.md).

"""

def main() -> int:
    drafts = sorted(HERE.glob("fn_*.sql")) + sorted(HERE.glob("sn_*.sql"))
    if not drafts:
        print("no draft files (fn_*.sql / sn_*.sql) found", file=sys.stderr)
        return 1
    parts = [HEADER]
    for d in drafts:
        parts.append(f"\n-- =====================================================================\n"
                     f"-- source: namegen/{d.name}\n"
                     f"-- =====================================================================\n\n")
        parts.append(d.read_text(encoding="utf-8").rstrip() + "\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    total_rows = sum(p.read_text(encoding="utf-8").count("(") for p in drafts)
    print(f"wrote {OUT.name}: {len(drafts)} drafts merged")
    return 0

if __name__ == "__main__":
    sys.exit(main())
